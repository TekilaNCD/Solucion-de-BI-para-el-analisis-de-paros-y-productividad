-- Justificación de índices (patrones de consulta analítica):
--  * Casi toda consulta filtra/agrupa por periodo y máquina → índice compuesto
--    (maquina_key, fecha_key) en cada hecho; sirve también para comparativos año vs año.
--  * Pareto y drill-down de paros agrupan por paro_key → índice en fact_paro(paro_key)
--    con INCLUDE de la medida para permitir index-only scans.
--  * Las FK de hechos se indexan para que los JOIN estrella usen hash/merge eficientes
--    y para que los borrados en dimensiones no hagan full scan.
--  * fecha_key solo (BRIN no aplica: los hechos del Excel no llegan ordenados por fecha).

CREATE INDEX IF NOT EXISTS ix_fpt_maquina_fecha ON dw.fact_produccion_turno (maquina_key, fecha_key);
CREATE INDEX IF NOT EXISTS ix_fpt_fecha         ON dw.fact_produccion_turno (fecha_key);
CREATE INDEX IF NOT EXISTS ix_fpt_referencia    ON dw.fact_produccion_turno (referencia_key);
CREATE INDEX IF NOT EXISTS ix_fpt_turno         ON dw.fact_produccion_turno (turno_key);
CREATE INDEX IF NOT EXISTS ix_fpt_operario      ON dw.fact_produccion_turno (operario_key);

CREATE INDEX IF NOT EXISTS ix_fp_maquina_fecha  ON dw.fact_paro (maquina_key, fecha_key);
CREATE INDEX IF NOT EXISTS ix_fp_paro           ON dw.fact_paro (paro_key) INCLUDE (horas_paro);
CREATE INDEX IF NOT EXISTS ix_fp_registro       ON dw.fact_paro (registro_id);
CREATE INDEX IF NOT EXISTS ix_fp_fecha          ON dw.fact_paro (fecha_key);

CREATE INDEX IF NOT EXISTS ix_fno_maquina_fecha ON dw.fact_no_operacion (maquina_key, fecha_key);
CREATE INDEX IF NOT EXISTS ix_fno_causa         ON dw.fact_no_operacion (causa_key);

CREATE INDEX IF NOT EXISTS ix_paro_jerarquia    ON dw.dim_paro (area_impacto, codigo_paro, subsistema_codigo);
CREATE INDEX IF NOT EXISTS ix_fecha_anio_mes    ON dw.dim_fecha (anio, mes);

-- ----------------------------- Auditoría -------------------------------------
CREATE TABLE IF NOT EXISTS audit.etl_ejecucion (
    ejecucion_id   bigint      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    inicio         timestamptz NOT NULL DEFAULT now(),
    fin            timestamptz,
    estado         varchar(12) NOT NULL DEFAULT 'EN CURSO',
    archivo_fuente text,
    hash_fuente    char(64),                          -- SHA-256 del Excel procesado
    filas_leidas   integer,
    mensaje        text
);

CREATE TABLE IF NOT EXISTS audit.calidad_regla (
    ejecucion_id     bigint  NOT NULL REFERENCES audit.etl_ejecucion(ejecucion_id) ON DELETE CASCADE,
    regla            varchar(6)  NOT NULL,
    dimension_dq     varchar(20) NOT NULL,             -- completitud, unicidad, validez, consistencia, exactitud
    descripcion      text    NOT NULL,
    accion           text    NOT NULL,
    filas_afectadas  integer NOT NULL,
    filas_antes      integer,
    filas_despues    integer,
    PRIMARY KEY (ejecucion_id, regla)
);

CREATE TABLE IF NOT EXISTS audit.reconciliacion (
    ejecucion_id    bigint  NOT NULL REFERENCES audit.etl_ejecucion(ejecucion_id) ON DELETE CASCADE,
    metrica         varchar(60) NOT NULL,
    valor_fuente    numeric(14,4),
    valor_cargado   numeric(14,4),
    diferencia      numeric(14,4),
    explicacion     text,
    PRIMARY KEY (ejecucion_id, metrica)
);
