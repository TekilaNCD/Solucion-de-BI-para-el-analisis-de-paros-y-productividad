-- =============================================================================
-- 02_dimensiones.sql  ·  Dimensiones conformadas del modelo dimensional
-- Convención: *_key = llave subrogada (PK); *_codigo / *_nk = llave natural.
-- Fila -1 = "Sin registro / No aplica" en cada dimensión (evita FK nulas en hechos).
-- =============================================================================

-- -----------------------------------------------------------------------------
-- dim_fecha  (construida por nosotros) · Jerarquía: Año > Semestre > Trimestre > Mes > Día
-- -----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS dw.dim_fecha (
    fecha_key        integer     PRIMARY KEY,            -- AAAAMMDD
    fecha            date        NOT NULL UNIQUE,
    anio             smallint    NOT NULL,
    semestre         smallint    NOT NULL CHECK (semestre BETWEEN 1 AND 2),
    trimestre        smallint    NOT NULL CHECK (trimestre BETWEEN 1 AND 4),
    mes              smallint    NOT NULL CHECK (mes BETWEEN 1 AND 12),
    nombre_mes       varchar(12) NOT NULL,
    anio_mes         char(7)     NOT NULL,               -- '2024-05' (orden cronológico en texto)
    semana_iso       smallint    NOT NULL,
    dia_mes          smallint    NOT NULL,
    dia_semana       smallint    NOT NULL CHECK (dia_semana BETWEEN 1 AND 7),  -- 1 = lunes
    nombre_dia       varchar(10) NOT NULL,
    es_fin_semana    boolean     NOT NULL,
    es_festivo       boolean     NOT NULL DEFAULT false, -- festivos Colombia (Ley 51 de 1983)
    nombre_festivo   varchar(80),
    es_dia_habil     boolean     NOT NULL
);
COMMENT ON TABLE dw.dim_fecha IS 'Calendario 2022-2027 con festivos de Colombia. Construida por el ETL (no existe en la fuente).';

-- -----------------------------------------------------------------------------
-- dim_turno  (construida por nosotros) · Jerarquía: Esquema de turnos > Jornada > Turno
-- -----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS dw.dim_turno (
    turno_key      smallint     PRIMARY KEY,
    turno_codigo   varchar(6)   NOT NULL UNIQUE,
    descripcion    varchar(40)  NOT NULL,              -- texto tal como aparece en el formato
    hora_inicio    time,
    hora_fin       time,
    duracion_h     numeric(4,1),
    esquema        varchar(10)  NOT NULL,              -- 3x8, 2x12, 1x10.5
    jornada        varchar(10)  NOT NULL               -- Diurno / Mixto / Nocturno
);
COMMENT ON TABLE dw.dim_turno IS 'Turnos normalizados. La fuente guarda el turno como texto libre (y a veces en la columna equivocada).';

-- -----------------------------------------------------------------------------
-- dim_maquina · Jerarquía: Planta > Línea de producto > Máquina
-- -----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS dw.dim_maquina (
    maquina_key       smallint     PRIMARY KEY,
    maquina_codigo    varchar(20)  NOT NULL UNIQUE,     -- Vinilos_1..Vinilos_4
    nombre            varchar(60)  NOT NULL,
    linea_producto    varchar(40)  NOT NULL,
    planta            varchar(40)  NOT NULL,
    factor_velocidad  numeric(4,2) NOT NULL DEFAULT 1,  -- hoja "Tiempos": 1,1 / 1,16 / 1 / 1
    activa            boolean      NOT NULL DEFAULT true
);

-- -----------------------------------------------------------------------------
-- dim_referencia  · SCD TIPO 2 (bonificación)
-- Jerarquía: Marca > Presentación (cc) > Referencia
-- La tasa ideal (pacas/hora) es un estándar de ingeniería que cambia en el tiempo:
-- si se modifica, se cierra la versión vigente y se abre una nueva, para que el
-- rendimiento histórico se siga calculando con la meta que existía en ese momento.
-- -----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS dw.dim_referencia (
    referencia_key          integer      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    referencia_nk           varchar(60)  NOT NULL,      -- nombre normalizado (llave natural)
    marca                   varchar(30)  NOT NULL,
    presentacion_cc         smallint,
    num_colores             smallint,
    unidades_por_paca       integer,
    tasa_estandar_pacas_h   numeric(8,2),               -- 72 und/min ÷ unidades por paca (Excel)
    tasa_ideal_pacas_h      numeric(8,2),               -- meta usada en Rendimiento/OEE
    fuente_tasa             varchar(40),                -- 'Estándar Excel' / 'P95 histórico' / ...
    valido_desde            date         NOT NULL DEFAULT DATE '2000-01-01',
    valido_hasta            date         NOT NULL DEFAULT DATE '9999-12-31',
    es_actual               boolean      NOT NULL DEFAULT true,
    version                 smallint     NOT NULL DEFAULT 1,
    CONSTRAINT ck_ref_vigencia CHECK (valido_hasta >= valido_desde),
    CONSTRAINT uq_ref_version UNIQUE (referencia_nk, valido_desde)
);
-- Solo una versión vigente por referencia
CREATE UNIQUE INDEX IF NOT EXISTS ux_ref_actual ON dw.dim_referencia (referencia_nk) WHERE es_actual;

-- -----------------------------------------------------------------------------
-- dim_persona  · role-playing: "operario" (quien opera) y "persona involucrada" (quien atiende el paro)
-- Seudonimizada: solo alias. La identidad real vive en seguro.persona_identidad.
-- -----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS dw.dim_persona (
    persona_key   integer      PRIMARY KEY,
    alias         varchar(12)  NOT NULL UNIQUE,         -- OP-001, MT-004 ...
    rol           varchar(30)  NOT NULL                 -- Operaria/o, Mantenimiento/Apoyo, Sin registro
);

CREATE TABLE IF NOT EXISTS seguro.persona_identidad (
    persona_key        integer PRIMARY KEY REFERENCES dw.dim_persona(persona_key),
    nombre_normalizado varchar(80) NOT NULL UNIQUE,
    variantes_origen   text[]      NOT NULL               -- cómo aparece escrito en el Excel
);

-- -----------------------------------------------------------------------------
-- dim_paro  · Jerarquía de paros aplanada (ragged → balanceada)
-- Área de impacto > Código de paro > Subsistema > Componente
-- Una fila por hoja del árbol. Niveles no informados se rellenan con "Sin especificar"
-- / "No aplica" para que el drill-down de Power BI funcione sin huecos.
-- -----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS dw.dim_paro (
    paro_key            integer      PRIMARY KEY,
    area_impacto        varchar(40)  NOT NULL,
    codigo_paro         char(2)      NOT NULL,          -- '01'..'18'
    nombre_paro         varchar(80)  NOT NULL,
    codigo_nombre       varchar(90)  NOT NULL,          -- '[01] Falla del sistema ...'
    subsistema_codigo   varchar(8)   NOT NULL,          -- '1.2' | 'N/A' | 'S/E'
    subsistema_nombre   varchar(80)  NOT NULL,
    componente_codigo   varchar(8)   NOT NULL,          -- '1.2.D' | 'N/A' | 'S/E'
    componente_nombre   varchar(80)  NOT NULL,
    es_programado       boolean      NOT NULL,          -- clasificación OEE construida por el equipo
    categoria_oee       varchar(40)  NOT NULL,          -- 'Paro programado' | 'Pérdida de disponibilidad'
    origen              varchar(30)  NOT NULL DEFAULT 'Catálogo P-MTO-22',
    CONSTRAINT uq_paro_hoja UNIQUE (codigo_paro, subsistema_codigo, componente_codigo)
);

-- -----------------------------------------------------------------------------
-- dim_causa_no_operacion · homologa los dos catálogos de "Tipo de paro" (legado y v1)
-- Jerarquía: Área responsable > Causa homologada > Texto origen
-- -----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS dw.dim_causa_no_operacion (
    causa_key          integer      PRIMARY KEY,
    texto_origen       varchar(90)  NOT NULL UNIQUE,
    causa_homologada   varchar(60)  NOT NULL,
    area_responsable   varchar(30)  NOT NULL,
    catalogo           varchar(20)  NOT NULL            -- 'Legado' | 'P-MTO-22 v1'
);
