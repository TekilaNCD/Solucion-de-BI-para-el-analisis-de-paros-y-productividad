-- -----------------------------------------------------------------------------
-- ops.fact_produccion_hora
-- GRANO: una fila por máquina × hora de producción (lectura "hora a hora").
-- Hoy la alimenta el simulador; mañana la alimentaría el PLC/SCADA.
-- Comparte dimensiones conformadas con el DW (ver matriz de bus).
-- -----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS ops.fact_produccion_hora (
    lectura_id                 bigint       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ts                         timestamptz  NOT NULL,          -- instante en que se recibe la lectura
    fecha_key                  integer      NOT NULL REFERENCES dw.dim_fecha(fecha_key),
    maquina_key                smallint     NOT NULL REFERENCES dw.dim_maquina(maquina_key),
    turno_key                  smallint     NOT NULL REFERENCES dw.dim_turno(turno_key),
    referencia_key             integer      NOT NULL REFERENCES dw.dim_referencia(referencia_key),
    operario_key               integer      NOT NULL REFERENCES dw.dim_persona(persona_key),
    paro_key                   integer      REFERENCES dw.dim_paro(paro_key),   -- causa principal de la hora
    minutos_disponibles        numeric(5,2) NOT NULL DEFAULT 60 CHECK (minutos_disponibles > 0),
    minutos_paro_programado    numeric(5,2) NOT NULL DEFAULT 0 CHECK (minutos_paro_programado >= 0),
    minutos_paro_no_programado numeric(5,2) NOT NULL DEFAULT 0 CHECK (minutos_paro_no_programado >= 0),
    pacas_producidas           numeric(8,2) NOT NULL CHECK (pacas_producidas >= 0),
    pacas_rechazadas           numeric(8,2) NOT NULL DEFAULT 0 CHECK (pacas_rechazadas >= 0),
    tasa_ideal_pacas_h         numeric(8,2) NOT NULL CHECK (tasa_ideal_pacas_h > 0),
    origen                     varchar(12)  NOT NULL DEFAULT 'SIMULADOR',
    CONSTRAINT ck_paros_hora CHECK (minutos_paro_programado + minutos_paro_no_programado <= minutos_disponibles),
    CONSTRAINT ck_rechazo CHECK (pacas_rechazadas <= pacas_producidas)
);
-- Consultas típicas de Grafana: "últimos N minutos" y "última lectura por máquina"
CREATE INDEX IF NOT EXISTS brin_fph_ts        ON ops.fact_produccion_hora USING brin (ts);
CREATE INDEX IF NOT EXISTS ix_fph_maquina_ts  ON ops.fact_produccion_hora (maquina_key, ts DESC);

-- Control del simulador (permite forzar una falla en vivo desde DBeaver)
CREATE TABLE IF NOT EXISTS ops.sim_control (
    maquina_codigo  varchar(20) PRIMARY KEY REFERENCES dw.dim_maquina(maquina_codigo),
    modo            varchar(10) NOT NULL DEFAULT 'normal'
                    CHECK (modo IN ('normal','falla','lento','parado','calidad')),
    actualizado_en  timestamptz NOT NULL DEFAULT now()
);

-- Bitácora de alertas recibidas desde Grafana (webhook → alert-receiver → esta tabla)
CREATE TABLE IF NOT EXISTS ops.alerta_evento (
    alerta_id     bigint      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    recibido_en   timestamptz NOT NULL DEFAULT now(),
    estado        varchar(10) NOT NULL,          -- firing / resolved
    regla         varchar(120),
    maquina       varchar(20),
    valor         text,
    resumen       text,
    payload       jsonb
);
CREATE INDEX IF NOT EXISTS ix_alerta_recibido ON ops.alerta_evento (recibido_en DESC);
