-- -----------------------------------------------------------------------------
-- fact_produccion_turno
-- GRANO: una fila por registro de turno de una máquina
--        (fecha × máquina × turno × operaria × referencia), tal como se diligencia
--        el formato "hora a hora" con el botón "Ingreso total".
-- Tipo: hecho transaccional de periodo (medidas aditivas en horas y pacas).
-- -----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS dw.fact_produccion_turno (
    registro_id                bigint       PRIMARY KEY,           -- = fila del Excel (linaje directo)
    fecha_key                  integer      NOT NULL REFERENCES dw.dim_fecha(fecha_key),
    maquina_key                smallint     NOT NULL REFERENCES dw.dim_maquina(maquina_key),
    turno_key                  smallint     NOT NULL REFERENCES dw.dim_turno(turno_key),
    referencia_key             integer      NOT NULL REFERENCES dw.dim_referencia(referencia_key),
    operario_key               integer      NOT NULL REFERENCES dw.dim_persona(persona_key),
    horas_trabajadas           numeric(6,2) NOT NULL CHECK (horas_trabajadas >= 0),
    horas_paro_total           numeric(8,4) NOT NULL DEFAULT 0 CHECK (horas_paro_total >= 0),
    horas_paro_programado      numeric(8,4) NOT NULL DEFAULT 0 CHECK (horas_paro_programado >= 0),
    horas_paro_no_programado   numeric(8,4) NOT NULL DEFAULT 0 CHECK (horas_paro_no_programado >= 0),
    horas_planificadas         numeric(8,4) NOT NULL DEFAULT 0 CHECK (horas_planificadas >= 0),  -- trabajadas − programado
    horas_operativas           numeric(8,4) NOT NULL DEFAULT 0 CHECK (horas_operativas >= 0),    -- planificadas − no programado
    horas_reproceso            numeric(8,4) NOT NULL DEFAULT 0,
    pacas_producidas_origen    numeric(10,2),                      -- valor crudo (para reconciliar)
    pacas_producidas           numeric(10,2) CHECK (pacas_producidas >= 0),  -- NULL si atípico
    tasa_ideal_pacas_h         numeric(8,2),                       -- copia de la meta vigente (SCD2)
    pacas_ideales              numeric(10,2),                      -- horas_operativas × tasa ideal
    pacas_meta_turno           numeric(10,2),                      -- horas_planificadas × tasa ideal
    flag_pacas_atipicas        boolean      NOT NULL DEFAULT false,
    flag_paro_excede_turno     boolean      NOT NULL DEFAULT false,
    flag_turno_recuperado      boolean      NOT NULL DEFAULT false,
    observaciones              text
);
COMMENT ON TABLE dw.fact_produccion_turno IS 'Grano: 1 fila = 1 registro de turno (fecha, máquina, turno, operaria, referencia). Incluye los paros de las filas de subcódigo asociadas.';

-- -----------------------------------------------------------------------------
-- fact_paro
-- GRANO: una fila por código de paro (y subcódigo) registrado en una fila del formato
--        → registro × código × subcódigo. Resultado de despivotar las 18 parejas
--        "Codigo de paro N / Codigo N en horas".
-- -----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS dw.fact_paro (
    paro_evento_id            bigint       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fila_excel                integer      NOT NULL,
    registro_id               bigint       REFERENCES dw.fact_produccion_turno(registro_id),  -- NULL = subcódigo huérfano
    tipo_fila                 varchar(12)  NOT NULL CHECK (tipo_fila IN ('principal','subcodigo')),
    fecha_key                 integer      NOT NULL REFERENCES dw.dim_fecha(fecha_key),
    maquina_key               smallint     NOT NULL REFERENCES dw.dim_maquina(maquina_key),
    turno_key                 smallint     NOT NULL REFERENCES dw.dim_turno(turno_key),
    referencia_key            integer      NOT NULL REFERENCES dw.dim_referencia(referencia_key),
    operario_key              integer      NOT NULL REFERENCES dw.dim_persona(persona_key),
    paro_key                  integer      NOT NULL REFERENCES dw.dim_paro(paro_key),
    persona_involucrada_key   integer      NOT NULL REFERENCES dw.dim_persona(persona_key),
    area_involucrada          varchar(30)  NOT NULL DEFAULT 'No aplica',   -- dimensión degenerada
    minutos_paro              numeric(8,2) NOT NULL CHECK (minutos_paro > 0),
    horas_paro                numeric(8,4) NOT NULL CHECK (horas_paro > 0),
    CONSTRAINT uq_paro_fila_codigo UNIQUE (fila_excel, paro_key)
);
COMMENT ON TABLE dw.fact_paro IS 'Grano: 1 fila = 1 código/subcódigo de paro con minutos > 0 en una fila del formato.';

-- -----------------------------------------------------------------------------
-- fact_no_operacion
-- GRANO: una fila por registro de horas no trabajadas de una máquina en un día
--        (máquina parada todo o parte del día: sin programación, ventas, materia prima...).
-- -----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS dw.fact_no_operacion (
    no_operacion_id     bigint       PRIMARY KEY,                -- = fila del Excel
    fecha_key           integer      NOT NULL REFERENCES dw.dim_fecha(fecha_key),
    maquina_key         smallint     NOT NULL REFERENCES dw.dim_maquina(maquina_key),
    turno_key           smallint     NOT NULL REFERENCES dw.dim_turno(turno_key),
    causa_key           integer      NOT NULL REFERENCES dw.dim_causa_no_operacion(causa_key),
    horas_no_operadas   numeric(6,2) NOT NULL CHECK (horas_no_operadas > 0),
    observacion_paro    varchar(120)
);
COMMENT ON TABLE dw.fact_no_operacion IS 'Grano: 1 fila = 1 registro de horas no trabajadas (máquina × día × causa).';
